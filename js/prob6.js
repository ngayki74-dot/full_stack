//arthmetic operations            +,-,*,/,%,**
let a = 10;
let b = 20;
let c =3;
console.log( a + b);                // Addition                   10 + 20 = 30       output : 30
console.log( a - b);                // Subtraction                10 - 20 = -10      output : -10
console.log( a * b);                // Multiplication             10 * 20 = 200      output : 200
console.log( a / b);                // Division                   10 / 20 = 0.5      output : 0.5
console.log( a % b);                // Modulus                    10 % 20 = 10       output : 10
console.log( a ** 2);               // Exponentiation (power)     10 ** 2 = 100      output : 100
console.log(b%c);                  // Modulus                     20 % 3 = 2         output : 2



//increment and decrement         ++,--
let x = 5;
console.log(x++);               // Post-increment             output : 5
console.log(x);                                            // output : 6
console.log(++x);               // Pre-increment              output : 7
console.log(x--);               // Post-decrement             output : 7
console.log(x);                 // output : 6
console.log(--x);               // Pre-decrement              output : 5
console.log(x);                                             // output : 5

