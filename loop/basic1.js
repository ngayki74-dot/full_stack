//iecrement /decrement
let p = 10
p = p + 5;                          // p = p + 5                output : 15
console.log(p);
p -= 3;                          // p = p - 3                output : 12
console.log(p);
p *= 2;                          // p = p * 2                output : 24
console.log(p);
p /= 4;                          // p = p / 4                output : 6
console.log(p);
p %= 4;                          // p = p % 4                output : 2
console.log(p);
p **= 3;                         // p = p ** 3               output : 8
console.log(p);        
